// Helper functions
function getProjectById(id) {
  if (!id) return portfolioProjects[0];
  const found = portfolioProjects.find(p => p.id.toLowerCase() === id.toLowerCase());
  return found || portfolioProjects[0];
}

function getRelatedProjects(currentId, limit = 3) {
  return portfolioProjects.filter(p => p.id !== currentId).slice(0, limit);
}
